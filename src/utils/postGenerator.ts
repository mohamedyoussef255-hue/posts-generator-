export async function generatePostsBatch(
  params: GeneratePostsParams,
  settings: AdminSettings
): Promise<{ posts: GeneratedPost[]; source: 'local' | 'external'; warning?: string }> {
  const safeCount = Math.min(20, Math.max(1, Math.round(params.count)));
  const safeMinLines = Math.max(5, Math.round(params.minLines));

  if (settings.externalAi.enabled && settings.externalAi.endpointUrl.trim()) {
    try {
      const headers: Record<string, string> = {
        'Content-Type': 'application/json',
      };
      if (settings.externalAi.apiToken.trim()) {
        headers['Authorization'] = `Bearer ${settings.externalAi.apiToken.trim()}`;
      }

      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 12000);

      const response = await fetch(settings.externalAi.endpointUrl.trim(), {
        method: 'POST',
        headers,
        signal: controller.signal,
        body: JSON.stringify({
          topic: params.topic,
          audience: params.audience,
          ageGroup: params.ageGroup,
          dialect: params.dialect,
          category: params.category,
          angle: params.angle,
          count: safeCount,
          minLines: safeMinLines,
          model: settings.externalAi.modelName || undefined,
          temperature: settings.externalAi.creativity,
        }),
      });
      clearTimeout(timeoutId);

      if (response.ok) {
        const data = await response.json();
        const rawPosts: unknown[] = Array.isArray(data?.posts)
          ? data.posts
          : Array.isArray(data)
            ? data
            : [];

        if (rawPosts.length > 0) {
          const mapped: GeneratedPost[] = rawPosts
            .slice(0, safeCount)
            .map((entry, index) => {
              const text =
                typeof entry === 'string'
                  ? entry
                  : typeof (entry as { text?: string })?.text === 'string'
                    ? (entry as { text: string }).text
                    : '';
              const angleLabel =
                typeof (entry as { angleLabel?: string })?.angleLabel === 'string'
                  ? (entry as { angleLabel: string }).angleLabel
                  : params.angle;

              return {
                id: Date.now() + index,
                text: text.trim(),
                dialect: params.dialect,
                category: params.category,
                angleLabel,
                image: null,
                phoneNumber: params.defaultPhone,
                isEditing: false,
                status: 'جاهز للجدولة',
              };
            })
            .filter((p) => p.text.length > 0);

          if (mapped.length > 0) {
            return { posts: mapped, source: 'external' };
          }
        }
      }
      return {
        posts: buildLocalPosts(params, safeCount, safeMinLines),
        source: 'local',
        warning:
          'تعذر الحصول على استجابة من المحرك الخارجي، تم التوليد بالمحرك المحلي بنجاح.',
      };
    } catch {
      return {
        posts: buildLocalPosts(params, safeCount, safeMinLines),
        source: 'local',
        warning: 'تعذر الاتصال بالمحرك الخارجي، تم التوليد تلقائياً بالمحرك المحلي.',
      };
    }
  }

  return {
    posts: buildLocalPosts(params, safeCount, safeMinLines),
    source: 'local',
  };
}

function buildLocalPosts(
  params: GeneratePostsParams,
  count: number,
  minLines: number
): GeneratedPost[] {
  const domain = resolveDomain(params.category);
  const ctx: TemplateContext = {
    topic: params.topic.trim(),
    audienceLabel: params.audience.trim() || defaultAudienceForDomain(domain),
    ageLabel:
      params.ageGroup === 'الكل'
        ? 'مختلف الأعمار'
        : `الفئة العمرية ${params.ageGroup} سنة`,
    category: params.category,
    domain,
    tagTopic: sanitizeHashtag(params.topic),
    tagCategory: sanitizeHashtag(params.category),
  };

  const allTemplates = buildTemplates(domain, params.dialect);

  let orderedTemplates: AngleTemplate[];
  if (params.angle === 'متنوع شامل') {
    orderedTemplates = allTemplates;
  } else {
    const matching = allTemplates.filter((t) => t.angleName === params.angle);
    const others = allTemplates.filter((t) => t.angleName !== params.angle);
    orderedTemplates = [...matching, ...others];
  }

  const domainTag: Record<DomainType, string> = {
    residential: '#المجتمع_السكني',
    social: '#النشاط_الاجتماعي',
    lifestyle: '#الحياة_اليومية',
    business: '#منشورات_فيسبوك',
  };

  const posts: GeneratedPost[] = [];
  for (let i = 0; i < count; i++) {
    const tpl = orderedTemplates[i % orderedTemplates.length];
    const baseLines = tpl.build(ctx);
    const bodyLines = padToMinLines(baseLines, minLines, params.dialect, ctx);

    const hashtags = `#${ctx.tagTopic} #${ctx.tagCategory} ${domainTag[domain]}`;
    const [hook, ...rest] = bodyLines;
    const fullText = `${hook}\n\n${rest.join('\n')}\n\n${hashtags}`;

    posts.push({
      id: Date.now() + i,
      text: fullText,
      dialect: params.dialect,
      category: params.category,
      angleLabel: tpl.label,
      image: null,
      phoneNumber: params.defaultPhone,
      isEditing: false,
      status: 'جاهز للجدولة',
    });
  }

  return posts;
}

export function countContentLines(text: string): number {
  return text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0 && !line.startsWith('#')).length;
}
